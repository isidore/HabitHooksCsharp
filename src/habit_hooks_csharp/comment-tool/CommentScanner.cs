using System.Text;
using System.Text.Json;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

public static class CommentScanner
{
    const int MaxSingleLineChars = 10;
    const int MaxBlockChars = 15;

    public static string Scan(IEnumerable<string> paths)
    {
        var files = paths.Where(File.Exists).ToArray();
        var issues = files.SelectMany(CommentsInFile).ToArray();
        if (issues.Length == 0)
        {
            return "[]";
        }

        var findings = new[]
        {
            new Finding("non-essential-comment", new object(), issues)
        };

        return JsonSerializer.Serialize(findings, new JsonSerializerOptions
        {
            PropertyNamingPolicy = JsonNamingPolicy.CamelCase
        });
    }

    static IEnumerable<Issue> CommentsInFile(string path)
    {
        var text = SourceText.From(File.ReadAllText(path));
        var tree = CSharpSyntaxTree.ParseText(text, path: path);
        var root = tree.GetRoot();

        return root.DescendantTrivia()
            .Where(IsReportable)
            .Select(trivia => ToIssue(path, trivia, tree));
    }

    static bool IsExempt(string text) =>
        text.Contains("ReSharper disable") || text.Contains("<auto-generated");

    static bool IsReportable(SyntaxTrivia trivia)
    {
        var text = trivia.ToString().Trim();
        if (IsExempt(text)) return false;

        return trivia.Kind() switch
        {
            SyntaxKind.SingleLineCommentTrivia => text.Length >= MaxSingleLineChars,
            SyntaxKind.MultiLineCommentTrivia => text.Length >= MaxBlockChars,
            SyntaxKind.SingleLineDocumentationCommentTrivia => text.Length >= MaxBlockChars,
            SyntaxKind.MultiLineDocumentationCommentTrivia => text.Length >= MaxBlockChars,
            _ => false
        };
    }

    static string Truncate(string text)
    {
        var collapsed = string.Join(' ', text.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries));
        return collapsed.Length > 50 ? collapsed[..50] + "..." : collapsed;
    }

    static string BlockKind(SyntaxTrivia trivia) => trivia.Kind() switch
    {
        SyntaxKind.SingleLineDocumentationCommentTrivia => "doc",
        SyntaxKind.MultiLineDocumentationCommentTrivia => "doc",
        SyntaxKind.MultiLineCommentTrivia => "block",
        _ => "single"
    };

    static Issue ToIssue(string path, SyntaxTrivia trivia, SyntaxTree tree)
    {
        var line = tree.GetLineSpan(trivia.Span).StartLinePosition.Line + 1;
        var kind = BlockKind(trivia);
        var message = $"{kind}-line comment: \"{Truncate(trivia.ToString())}\"";
        return new Issue(path, new IssueDetails(path, line, message, "comment:non-essential"));
    }
}

record Finding(string Smell, object Details, Issue[] Issues);
record Issue(string Key, IssueDetails Details);
record IssueDetails(string File, int Line, string Message, string Source);
